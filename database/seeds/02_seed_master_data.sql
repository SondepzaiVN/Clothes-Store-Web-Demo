            ON productColor.ProductCode = productSeed.ProductCode
        INNER JOIN @ColorSeed AS colorSeed
            ON colorSeed.Name = productColor.ColorName
        INNER JOIN dbo.Colors AS colorTable
            ON colorTable.Name = colorSeed.Name
    )
